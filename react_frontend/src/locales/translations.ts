const TAMIL_ITEM_MAP: Array<{ match: RegExp; ta: string }> = [
  { match: /^LARGE EGG$/i, ta: 'பெரிய முட்டை (Large Egg)' },
  { match: /^MEDIUM EGG$/i, ta: 'நடுத்தர முட்டை (Medium Egg)' },
  { match: /^SMALL EGG$/i, ta: 'சிறிய முட்டை (Small Egg)' },
  { match: /^BROKEN EGG$/i, ta: 'உடைந்த முட்டை (Broken Egg)' },
  { match: /^DIRTY EGG$/i, ta: 'அழுக்கு முட்டை (Dirty Egg)' },
  { match: /^LABOR$/i, ta: 'வேலையாட்கள் சம்பளம் (Labor)' },
  { match: /^ELECTRICITY(\s*BILL)?$/i, ta: 'மின்சாரக் கட்டணம் (EB)' },
  { match: /^EMI$/i, ta: 'வங்கி தவணை (EMI)' },
  { match: /LAYER\s*MASH/i, ta: 'லேயர் மாஷ் தீவனம் (Layer Mash)' },
  { match: /PRE[-\s]*LAYER\s*MASH|^PLM$/i, ta: 'ப்ரீ-லேயர் மாஷ் (Pre-Layer Mash)' },
  { match: /GROWER\s*MASH|\bGM\b/i, ta: 'குரோவர் மாஷ் (Grower Mash)' },
  { match: /CHICK\s*(CRUMBLE|MASH)|\bLCC\b/i, ta: 'குஞ்சு தீவனம் (Chick Crumble/Mash)' },
  { match: /SHELL\s*GRIT/i, ta: 'கிளிஞ்சல் (Shell Grit)' },
  { match: /^HEN BATCH SALE\s*-\s*(.+)$/i, ta: 'கழிவுக் கோழி விற்பனை - $1' },
];

export function translateItemName(itemName: string | undefined | null, lang: AppLanguage): string {
  if (!itemName) return '-';
  if (lang === 'en') return itemName;
  const trimmed = itemName.trim();
  for (const rule of TAMIL_ITEM_MAP) {
    if (rule.match.test(trimmed)) {
      return trimmed.replace(rule.match, rule.ta);
    }
  }
  return itemName;
}

export function translateStageTag(stage: string | undefined, lang: AppLanguage): string {
  if (!stage) return '';
  if (lang === 'en') return stage;
  switch (stage.toUpperCase()) {
    case 'LAYER':
      return 'முட்டை தீவனம்';
    case 'CHICK':
      return 'குஞ்சு தீவனம்';
    case 'GROWER':
      return 'குரோவர் தீவனம்';
    case 'PRELAYER':
    case 'PRE-LAYER':
      return 'ப்ரீ-லேயர்';
    default:
      return stage;
  }
}
